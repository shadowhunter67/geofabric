// Static browser profile: the THIN adapter between the page and the canonical Rust builder (RFC-004). It contains no plan semantics: what a
// viewport query, a filter, a count/group or a neighbour question means as a PlanGraph is defined once, in `crates/geo-plan`, and reached through
// `engine/lowering.ts` (the same code the gateway links natively; `web/test/plan.test.ts` proves byte-identical plans on 40 golden requests).
// This file only (1) hands the request and the published Source nodes to that builder, (2) turns its structured errors and the browser capability
// verdict into the gateway's `{error, message}` answers, and (3) estimates which row groups a viewport can touch (a physical-planning estimate for
// the Developer view, not plan semantics). No DOM, no fetch: unit-tested under node.

import { buildPlan, PlanBuildError } from "../engine/lowering.ts";
import type { PlanGraph } from "../engine/contract.ts";

/** The request as the UI posts it: the plan request (`geo-plan::PlanRequest`) plus transport fields the planner owns. */
export interface QueryReq {
  source: string; kind: string; bbox: [number, number, number, number]; crs: string;
  limit?: number; filter?: unknown; group_by?: string; sample_modulus?: number; with?: { source: string; [k: string]: unknown };
  engine?: string; browser?: boolean; client?: unknown;
}

/** One column as `/api/sources` reports it. */
export interface ColumnMeta { name: string; type: unknown }
export interface RowGroupStat { index: number; rows: number; bytes: number; bbox: [number, number, number, number] | null }
/** A source of the static pack: its `SourceMeta`, its IR Source node (generated by the Rust reader from the file's footer), the public file and the per-row-group boxes. */
export interface StaticSource {
  id: string; size_bytes: number; rows: number; row_groups: number; crs: string; geometry_column: string; geometry_type: string;
  bbox: [number, number, number, number] | null; columns: ColumnMeta[]; file: string; row_group_stats: RowGroupStat[];
  /** `{"op":"source","uri":"demo/v1/<file>","format":"geo_parquet","schema":{...},"statistics":{...}}`: exactly what the gateway's `open_source` yields */
  ir_source: { uri: string; [k: string]: unknown };
}

/** An error the shim answers with the gateway's `{error, message}` shape (plus the structured `code` when the builder gave one) and an HTTP-like status. */
export class StaticError extends Error {
  code: string;
  status: number;
  planCode?: string;
  constructor(status: number, code: string, message: string, planCode?: string) {
    super(message);
    this.code = code;
    this.status = status;
    this.planCode = planCode;
  }
}

/** The capability verdict as an answer: this plan needs operations the browser engine does not have. Nothing is dropped or approximated. */
export function serverRequired(missingOps: string[]): StaticError {
  return new StaticError(
    422,
    "server_required",
    `This analysis requires GeoFabric Server (the browser engine cannot run: ${missingOps.join(", ")}). This deployment is browser-only: DuckDB server and PostGIS are not part of it.`,
  );
}

export interface PlannedRequest {
  plan: PlanGraph;
  planJson: string;
  /** operations of the plan this deployment cannot run (empty = it can run all of it) */
  missingOps: string[];
  /** the Source node uri of the main dataset (the key the physical plan binds to a URL) */
  uri: string;
}

/**
 * Request -> PlanGraph through the canonical builder. Throws StaticError for a refused request (structured code kept); returns the plan even when
 * the browser cannot run it: the caller decides ("enabled" or "server required") from `missingOps`.
 */
export function planRequest(q: QueryReq, sources: StaticSource[]): PlannedRequest {
  const nodes: Record<string, unknown> = {};
  const main = sources.find((s) => s.id === q.source);
  if (main) nodes[main.id] = main.ir_source;
  const withId = q.with?.source;
  const second = withId ? sources.find((s) => s.id === withId) : undefined;
  if (second) nodes[second.id] = second.ir_source;
  let built;
  try {
    built = buildPlan(q, nodes);
  } catch (e) {
    if (e instanceof PlanBuildError) throw new StaticError(e.status, e.legacy, e.message, e.code);
    throw e;
  }
  const plan = built.plan;
  // the engine hint is a PLANNER input (not part of the request model): attached after the plan is built, never inside it
  if (q.engine) plan.hints = { preferred_engine: q.engine };
  return { plan, planJson: built.planJson, missingOps: built.browserMissingOps, uri: main!.ir_source.uri };
}

/** Row groups of `src` that can hold rows inside `bbox` (a row group without a box is always kept: nothing proves it can be skipped). */
export function prune(src: StaticSource, bbox: [number, number, number, number]) {
  const [x0, y0, x1, y1] = bbox;
  const kept = src.row_group_stats.filter((g) => !g.bbox || (g.bbox[0] <= x1 && g.bbox[2] >= x0 && g.bbox[1] <= y1 && g.bbox[3] >= y0));
  const sum = (f: (g: RowGroupStat) => number, gs: RowGroupStat[]) => gs.reduce((a, g) => a + f(g), 0);
  return {
    kept: kept.map((g) => g.index), skipped: src.row_group_stats.length - kept.length, total_row_groups: src.row_group_stats.length,
    total_rows: sum((g) => g.rows, src.row_group_stats), kept_rows: sum((g) => g.rows, kept),
    kept_bytes: sum((g) => g.bytes, kept), total_bytes: src.size_bytes, method: "covering_stats",
  };
}
