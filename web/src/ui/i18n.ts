const DICT: Record<Lang, Record<Key, string>> = { vi, en };

let current: Lang = "vi";
const listeners: (() => void)[] = [];

export function getLang(): Lang { return current; }
export function setLang(l: Lang): void {
  if (l === current) return;
  current = l;
  for (const f of listeners) f();
}
export function onLangChange(f: () => void): void { listeners.push(f); }

/** Translate `key`; `{name}` placeholders are replaced from `params`. Unknown keys return the key (visible, never throws). */
export function t(key: Key, params?: Record<string, string | number>): string {
  const s = DICT[current][key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`)) : s;
}

export function dictionary(l: Lang): Record<string, string> { return DICT[l]; }
